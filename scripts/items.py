TIER_ORDER = ["DECISIVE", "EVIDENCE", "MANUAL"]


def item_count():
    return sum(len(c["items"]) for c in CATEGORIES)


def coverage_by_item():
    """item number -> best tier any scanner check gives it (DECISIVE > EVIDENCE > MANUAL)."""
    cov = {n: "MANUAL" for n in range(1, item_count() + 1)}
    for _check, (nums, tier) in SCANNER_CHECKS.items():
        for n in nums:
            if TIER_ORDER.index(tier) < TIER_ORDER.index(cov[n]):
                cov[n] = tier
    return cov
